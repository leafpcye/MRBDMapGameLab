import { readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import path from "node:path";

const execFileAsync = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

let gitCommit = "unknown";
try {
  const { stdout } = await execFileAsync("git", ["rev-parse", "--short", "HEAD"], { cwd: root });
  gitCommit = stdout.trim() || "uncommitted";
} catch (error) {
  gitCommit = error?.code === 128 ? "uncommitted" : "unknown";
}

const buildInfo = {
  version: pkg.version,
  gitCommit,
  generatedAt: new Date().toISOString()
};

await writeFile(
  path.join(root, "build-info.js"),
  `// Generated by scripts/generate-build-info.mjs. Do not edit by hand.\nexport const BUILD_INFO = ${JSON.stringify(buildInfo, null, 2)};\n`,
  "utf8"
);
console.log(`Build info generated: v${buildInfo.version} (${buildInfo.gitCommit})`);

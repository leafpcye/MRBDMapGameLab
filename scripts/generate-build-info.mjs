import { mkdir, readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import path from "node:path";

const execFileAsync = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export async function resolveGitCommit() {
  const actionsCommit = process.env.GITHUB_SHA?.trim();
  if (actionsCommit) return actionsCommit.slice(0, 7);
  try {
    const { stdout } = await execFileAsync("git", ["rev-parse", "--short", "HEAD"], { cwd: root });
    return stdout.trim() || "uncommitted";
  } catch (error) {
    return error?.code === 128 ? "uncommitted" : "unknown";
  }
}

export async function generateBuildInfo(outputPath = path.join(root, "build-info.js")) {
  const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  const buildInfo = {
    version: pkg.version,
    gitCommit: await resolveGitCommit(),
    generatedAt: new Date().toISOString()
  };
  const absoluteOutput = path.resolve(outputPath);
  await mkdir(path.dirname(absoluteOutput), { recursive: true });
  await writeFile(
    absoluteOutput,
    `// Generated by scripts/generate-build-info.mjs. Do not edit by hand.\nexport const BUILD_INFO = ${JSON.stringify(buildInfo, null, 2)};\n`,
    "utf8"
  );
  return { buildInfo, outputPath: absoluteOutput };
}

function outputArgument(argv) {
  const index = argv.indexOf("--output");
  if (index === -1) return path.join(root, "build-info.js");
  if (!argv[index + 1]) throw new Error("--output requires a file path");
  return path.resolve(argv[index + 1]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { buildInfo, outputPath } = await generateBuildInfo(outputArgument(process.argv.slice(2)));
  console.log(`Build info generated: v${buildInfo.version} (${buildInfo.gitCommit})`);
  console.log(`Output: ${outputPath}`);
}
